import numpy as np


def L(ctx, code):
    """溢价率（%）或 None"""
    v = ctx.get("prem", {}).get(code)
    if v is None:
        return None
    try:
        x = float(v.get("prem", np.nan))
    except Exception:
        return None
    return None if not np.isfinite(x) else round(x, 2)


def _p(x, n=2):
    """把数值转成带符号百分号字符串（不做二次 % 格式化）"""
    if x is None:
        return "—"
    try:
        return ("{:+." + str(n) + "f}%").format(float(x))
    except Exception:
        return "—"


def _starts(ctx, key):
    """五起点：全部来自 data/_robust.json（执行时点价口径）"""
    r = ((ctx.get("robust") or {}).get(key) or {}).get("starts") or {}
    if not r:
        return "未计算"
    return " ｜ ".join("%s %s" % (k, _p(v, 2)) for k, v in r.items() if v is not None)


def _cost(ctx, key):
    """成本阶梯：zero / now / 0.2% / 0.3% / 0.5%"""
    c = ((ctx.get("robust") or {}).get(key) or {}).get("cost") or {}
    if not c:
        return "未计算"
    lab = (("zero", "零成本"), ("now", "现行"), ("t2", "0.2%"),
           ("t3", "0.3%"), ("h5", "0.5%"))
    return " ｜ ".join("%s %s" % (n, _p(c.get(k), 2)) for k, n in lab if c.get(k) is not None)


def _stopline(ctx):
    """线C 盘中止损开关：开/关两组的年化与回撤（14:45 执行口径）"""
    st = ((ctx.get("robust") or {}).get("lineC") or {}).get("stop") or {}
    if st.get("on") is None or st.get("off") is None:
        return "未计算"
    d = st["off"] - st["on"]
    verdict = ("关掉更优（年化 %+.2fpp）⇒ 建议复核 config 的 ENABLE_INTRADAY_STOP" % d
               if d > 0 else "维持开（关掉会少 %.2fpp）" % abs(d))
    return "开 %s ｜ 关 %s ⇒ %s" % (_p(st["on"]), _p(st["off"]), verdict)


