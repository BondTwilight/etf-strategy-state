"""两条资金线并行 vs 只做一条：用可得的年度数据做一次粗略配置测算

数据来源与局限（必须先声明）：
  · 抄底策略年度收益 = 本地回测（2021-2025，线上口径 V2）
  · 天基营年度收益   = 官网表4「新多空模型」（中证1000）
  · 只有 5 个年度样本 ⇒ 相关系数统计上极不可靠，只能看方向
  · 年度粒度会掩盖年内路径，真实回撤需月度数据
"""
import numpy as np

yrs = [2021, 2022, 2023, 2024, 2025]
a = np.array([-22.88, 108.23, 3.26, 68.43, 45.85]) / 100.0     # 抄底
b = np.array([27.23, 18.61, 9.01, 93.31, 20.07]) / 100.0       # 天基营 新多空


def cagr(r):
    return np.prod(1 + np.asarray(r)) ** (1 / len(r)) - 1


def vol(r):
    return np.std(r, ddof=1)


print('年份    抄底      天基营    50/50并行')
for y, x, z in zip(yrs, a, b):
    print('%d  %7.2f%%  %7.2f%%  %7.2f%%' % (y, x * 100, z * 100, (0.5 * x + 0.5 * z) * 100))

comb = 0.5 * a + 0.5 * b
print('\n%-14s %9s %9s %9s' % ('', '抄底', '天基营', '50/50并行'))
print('%-14s %8.2f%% %8.2f%% %8.2f%%' % ('年化(5年)', cagr(a) * 100, cagr(b) * 100, cagr(comb) * 100))
print('%-14s %8.2f%% %8.2f%% %8.2f%%' % ('年度波动', vol(a) * 100, vol(b) * 100, vol(comb) * 100))
print('%-14s %8.2f  %8.2f  %8.2f' % ('年化/波动', cagr(a) / vol(a), cagr(b) / vol(b), cagr(comb) / vol(comb)))

# 风险平价：按波动率倒数配权（波动大的少配）
wa = (1 / vol(a)) / (1 / vol(a) + 1 / vol(b))
wb = 1 - wa
rp = wa * a + wb * b
print('\n【风险平价配权（按波动率倒数）】抄底 %.1f%% / 天基营 %.1f%%' % (wa * 100, wb * 100))
print('%-14s %8.2f%% %8.2f%%' % ('年化', cagr(rp) * 100, 0))
print('%-14s %8.2f%%' % ('年度波动', vol(rp) * 100))
print('%-14s %8.2f' % ('年化/波动', cagr(rp) / vol(rp)))
print('%-14s 最好 %+7.2f%%  最差 %+7.2f%%' % ('单年极值', rp.max() * 100, rp.min() * 100))

r = np.corrcoef(a, b)[0, 1]
print('\n相关系数 r = %.3f（5 个年度样本，只能看方向）' % r)

print('\n【单年最好 / 最差】')
for nm, s in (('抄底', a), ('天基营', b), ('50/50', comb)):
    print('  %-6s 最好 %+7.2f%%   最差 %+7.2f%%' % (nm, s.max() * 100, s.min() * 100))

# 空仓期买债的增益估算
print('\n【替代方案：不加第二条策略，只把闲置资金买债】')
expo = 0.195          # 抄底策略持仓日占比
for r_cash in (0.02, 0.025, 0.03):
    add = (1 - expo) * r_cash
    print('  闲置 %.1f%% 的时间按 %.1f%% 年化计息 → 增厚约 %+.2fpp/年 '
          '（%.2f%% → %.2f%%），零新增策略风险'
          % ((1 - expo) * 100, r_cash * 100, add * 100,
             cagr(a) * 100, (cagr(a) + add) * 100))
